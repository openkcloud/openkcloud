export function modelStats() {
  const byCategory: Record<ModelCategory, number> = {
    LLM: 0,
    Vision: 0,
    Multimodal: 0,
    Audio: 0,
    Embedding: 0,
    Diffusion: 0,
  };
  for (const m of REBELLIONS_MODELS) byCategory[m.category]++;
  return {
    total: REBELLIONS_MODELS.length,
    byCategory,
    byAuthor: Array.from(new Set(REBELLIONS_MODELS.map((m) => m.author))).length,
  };
}
